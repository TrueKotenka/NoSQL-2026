def main() -> None:
    documents = []
    for index, (title, description, category, channel, tags) in enumerate(ROWS, start=1):
        document = {
            "video_id": f"v{index:03d}",
            "title": title,
            "description": description,
            "category": category,
            "channel": channel,
            "tags": tags,
            "views": 3000 + (index * 1379) % 19000,
            "rating": round(3.5 + (index % 15) / 10, 1),
            "published_at": (date(2026, 1, 3) + timedelta(days=(index - 1) * 3)).isoformat(),
            "is_premium": index % 4 == 0,
            "duration_minutes": 7 + (index * 3) % 29,
        }
        if index % 3 == 0:
            document["subtitles"] = "ru"
        if index == 5:
            document["views"] = 12300
        documents.append(document)

    target = Path(__file__).resolve().parent.parent / "data" / "videos.json"
    target.write_text(json.dumps(documents, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{target}: {len(documents)} документов")


if __name__ == "__main__":
    main()
